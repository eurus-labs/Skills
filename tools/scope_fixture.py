#!/usr/bin/env python3
"""A small repository for the product-scope tests, written into a directory on demand.

Not under `fixtures/`: that tree holds deliberately broken projects other plugins are
evaluated against. This one is a test's own scaffolding and is built fresh each time.

What it holds, and why each file is there:

    src/shop/money.py, cart.py, invoice.py   the well-connected modules a `--top 2` keeps
    src/shop/runner.py                       entry point, no symbol: only a `__main__` guard
    src/shop/__init__.py, src/latest/__init__.py
                                             zero bytes: `empty` in the scope, never read or cited
    src/latest/feed.py                       low fan-in feature outside the first batch;
                                             `latest` must not be taken for a test
    src/shop/contest.py                      `contest` must not be taken for a test either
    src/shop/schema_pb2.py                   generated, by name
    src/shop/rates_table.py                  generated, by its header
    tests/test_cart.py                       a test, and the one file a citation may name
    third_party/slugify.py                   vendored
    examples/demo.py                         example source
    README.md                                an asset
    .github/skills/verify-shop/...           a feature map (optional)
"""

import os

FILES = {
    "README.md": "# shop\n\nA small shop library.\n",
    "src/shop/__init__.py": "",
    "src/shop/money.py": (
        '"""Money in cents."""\n\n\ndef to_cents(amount):\n    return int(round(amount * 100))\n'
        "\n\ndef show(cents):\n    return '%d.%02d' % divmod(cents, 100)\n"),
    "src/shop/cart.py": (
        "from shop.money import to_cents\n\n\nclass Cart(object):\n    def __init__(self):\n"
        "        self.lines = []\n\n    def add(self, sku, price, quantity):\n"
        "        self.lines.append((sku, to_cents(price), quantity))\n\n"
        "    def total(self):\n        return sum(p * q for _, p, q in self.lines)\n"),
    "src/shop/invoice.py": (
        "from shop.cart import Cart\nfrom shop.money import show\n\n\ndef render(basket):\n"
        "    return show(basket.total())\n"),
    "src/shop/runner.py": (
        "import shop.invoice\n\nif __name__ == '__main__':\n"
        "    print(shop.invoice.render(None))\n"),
    "src/shop/contest.py": "def enter(name):\n    return name.strip()\n",
    "src/shop/schema_pb2.py": (
        "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n"
        "DESCRIPTOR = None\n\n\ndef build():\n    return DESCRIPTOR\n"),
    "src/shop/rates_table.py": (
        "# Code generated by gen_rates.py; DO NOT EDIT.\nRATES = {}\n\n\n"
        "def rate(code):\n    return RATES.get(code)\n"),
    "src/latest/__init__.py": "",
    "src/latest/feed.py": (
        "def newest(items, count):\n    return sorted(items)[:count]\n"),
    "tests/test_cart.py": (
        "from shop.cart import Cart\n\n\ndef test_total():\n    c = Cart()\n"
        "    c.add('A', 1.5, 2)\n    assert c.total() == 300\n"),
    "third_party/slugify.py": "def slugify(text):\n    return text.lower()\n",
    "examples/demo.py": "def demo():\n    return 1\n",
    "docs/conf.py": "project = 'shop'\n",
}

FEATURE_MAP = {
    ".github/skills/verify-shop/SKILL.md": (
        "---\nname: verify-shop\ndescription: Verify the shop.\n---\n\n# verify-shop\n"),
    ".github/skills/verify-shop/references/features/README.md": (
        "# shop feature map\n\n## Index\n"
        "- [cart](cart.md) — owns: `src/shop/cart.py`, `tests/test_cart.py` — uses: "
        "`src/shop/money.py` — add lines, the total shown to the customer.\n"
        "- [invoice](invoice.md) — owns: `src/shop/invoice.py`, `src/shop/runner.py` "
        "— uses: `src/shop/money.py`,\n  `src/shop/cart.py` — the printed invoice.\n"
        "- [latest-feed](latest-feed.md) — owns: `src/latest/**` — the newest-items "
        "feed.\n\n## Full-sweep order\ncart, invoice, latest-feed.\n"),
    ".github/skills/verify-shop/references/features/cart.md": "# Cart\n\nThe cart.\n",
    ".github/skills/verify-shop/references/features/invoice.md": "# Invoice\n\nThe invoice.\n",
    ".github/skills/verify-shop/references/features/latest-feed.md":
        "# Latest feed\n\nThe feed.\n",
}


def write(root, feature_map=False):
    """Create the repository under `root` and return `root`."""
    tables = [FILES] + ([FEATURE_MAP] if feature_map else [])
    for table in tables:
        for rel, text in table.items():
            full = os.path.join(root, *rel.split("/"))
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w", encoding="utf-8") as fh:
                fh.write(text)
    return root
